// Generates src/fonts.js — base64-embedded Vazirmatn fonts so the Worker's PDF
// generation NEVER depends on the static-assets store (fixes production
// «فونت‌های PDF در assets یافت نشدند» when fonts are missing from a deployment).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = f => fs.readFileSync(path.join(root, 'public/fonts', f));
const b64 = buf => Buffer.from(buf).toString('base64');

const reg = b64(read('Vazirmatn-Regular.ttf'));
const bold = b64(read('Vazirmatn-Bold.ttf'));

const out = `// AUTO-GENERATED by scripts/gen-font-module.mjs — do not edit by hand.
// Vazirmatn TTFs embedded as base64 so src/pdf.js works even when the static
// assets are missing/stale on a deployment (the «فونت یافت نشد» bug).
export const VAZIR_REGULAR_B64 = '${reg}';
export const VAZIR_BOLD_B64 = '${bold}';
`;

fs.writeFileSync(path.join(root, 'src/fonts.js'), out);
console.log('src/fonts.js written:', (out.length / 1024).toFixed(0) + 'KB');
